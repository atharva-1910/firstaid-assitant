        f"{cur6['by_lang']['hi']['accuracy']:.2f} / {cur6['by_lang']['hinglish']['accuracy']:.2f} / {cur6['by_lang']['mr']['accuracy']:.2f} with {cur6['by_lang']['all']['dangerous']}. "
        "The remaining dangerous errors come from uncertainty cues attaching to the nearest word (\"not sure if **my father** is breathing\" read as breathing normally). "
        f"Letting uncertainty cover every safety fact in its clause raises accuracy to {prop6['by_lang']['all']['accuracy']:.2f} with "
        f"{prop6['by_lang']['all']['dangerous']} dangerous errors and no change on the safety suite or probe; a full ConText-style scope gets "
        f"{ctx6['by_lang']['all']['accuracy']:.2f}. The last misses (\"कोई दर्द या दबाव नहीं\") are lexicon gaps, not negation. "
        "The diagnostic set was drafted by Claude; the owners' 100-sentence sets are needed to confirm. Figure: `figures/e6_negation.png`.", "",
        "**7. Word overlap cannot verify a rephrased step (E7, Siddhi).** "
        f"Across {e7['pairs']} step/candidate pairs in four languages, a word-overlap verifier tuned to accept 95% of safe rewordings rejects only "
        f"{pct(v[vj]['negation_removed'])} of steps with \"do not\" removed and {pct(v[vj]['number_changed'])} with a changed number (\"20 minutes\" → \"2 minutes\"); "
        f"character F-score rejects {pct(v[vc]['negation_removed'])} and {pct(v[vc]['number_changed'])}. A guard written for exactly these edits catches them, "
        f"but still misses {pct(1 - v[vg]['antonym'])} of antonym swaps and rejects {pct(1 - v[vg]['polite_form'])} of harmless polite forms. "
        "This is the case for the trained mmBERT verifier; notebook 05 scores it on the same pairs. Figure: `figures/e7_verifier.png`.", "",
        "**8. Highlighted words are faithful, but the app's F4 words are incomplete (E8, Soham).** "
        f"Deleting a model's top-3 attributed words lowers P(emergency) by {e8['word']['top3']['comprehensiveness']:.2f} on average, against "
        f"{e8['word']['random3']['comprehensiveness']:.2f} for three random words. Deleting the app's own trigger words removes the rule alert in "
        f"{pct(e8['word']['rule_trigger_words']['rules_flip_rate'])} of emergencies: in the rest, other words also fire the rules but are not shown. "
        f"The character model's top word is one of the app's trigger words in {pct(e8['char']['rule_trigger_words']['model_top_word_is_trigger'])} of messages. "
